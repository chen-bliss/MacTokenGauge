enum L10n {
    static var language: AppLanguage = {
        let raw = UserDefaults.standard.string(forKey: "appLanguage") ?? ""
        return AppLanguage(rawValue: raw) ?? .system
    }()

    static var period: String { language.resolved == .zh ? "。" : ". " }

    static func s(_ key: LKey, _ choice: AppLanguage? = nil) -> String {
        let lang = (choice ?? language).resolved
        return pack(lang)[key] ?? pack(.en)[key] ?? key.rawValue
    }

    static func f(_ key: LKey, _ args: CVarArg...) -> String {
        String(format: s(key), locale: language.resolved.locale, arguments: args)
    }

    static func windowTitle(_ window: UsageWindow) -> String {
        switch window.id {
        case "cursor-total": return s(.thisMonth)
        case "cursor-auto": return "Auto"
        case "cursor-api": return "API"
        case "cursor-ondemand": return s(.onDemand)
        case "cursor-requests": return s(.monthRequests)
        case "five_hour": return s(.fiveHours)
        case "seven_day": return s(.sevenDays)
        case "seven_day_opus": return s(.opusWeek)
        case "seven_day_sonnet": return s(.sonnetWeek)
        case "seven_day_haiku": return s(.haikuWeek)
        case "extra_usage": return s(.extraUsage)
        default:
            if window.id.hasPrefix("extra-") {
                if window.id.hasSuffix("primary") || window.id.hasSuffix("secondary") {
                    let role = window.id.hasSuffix("primary") ? "primary" : "secondary"
                    return window.title + " · " + duration(window.windowSeconds, id: role)
                }
                return window.title
            }
            if window.id == "primary" || window.id == "secondary" {
                return duration(window.windowSeconds, id: window.id)
            }
            return window.title
        }
    }

    static func barTitle(id: String, accounts: [ProviderAccount]) -> String {
        if id == "battery" { return s(.batteryName) }
        let parts = id.split(separator: ".", maxSplits: 1).map(String.init)
        guard parts.count == 2 else { return id }
        let accountName = accounts.first { $0.id == parts[0] }?.name ?? parts[0]
        if let window = accounts.first(where: { $0.id == parts[0] })?.windows.first(where: { $0.id == parts[1] }) {
            return f(.pair, accountName, windowTitle(window))
        }
        let label: String
        switch parts[1] {
        case "primary": label = s(.fiveHours)
        case "secondary": label = s(.sevenDays)
        case "cursor-total": label = s(.thisMonth)
        case "cursor-auto": label = "Auto"
        case "cursor-api": label = "API"
        case "cursor-ondemand": label = s(.onDemand)
        case "cursor-requests": label = s(.monthRequests)
        case "five_hour": label = s(.fiveHours)
        case "seven_day": label = s(.sevenDays)
        case "seven_day_opus": label = s(.opusWeek)
        case "seven_day_sonnet": label = s(.sonnetWeek)
        default: label = parts[1]
        }
        return f(.pair, accountName, label)
    }

    private static func duration(_ seconds: TimeInterval?, id: String) -> String {
        guard let seconds else {
            return id == "primary" ? s(.shortWindow) : s(.longWindow)
        }
        let minutes = Int((seconds / 60).rounded())
        switch minutes {
        case 300: return s(.fiveHours)
        case 10_080: return s(.sevenDays)
        case 1_440: return s(.hours24)
        default:
            if minutes >= 1_440, minutes % 1_440 == 0 { return f(.nDays, minutes / 1_440) }
            if minutes >= 60, minutes % 60 == 0 { return f(.nHours, minutes / 60) }
            return id == "primary" ? s(.shortWindow) : s(.longWindow)
        }
    }

    private static func pack(_ language: AppLanguage) -> [LKey: String] {
        switch language {
        case .zh: return zh
        case .fr: return fr
        case .ru: return ru
        case .es: return es
        case .ar: return ar
        default: return en
        }
    }
}

