import SwiftUI

enum AppLanguage: String, CaseIterable, Identifiable {
    case system
    case ar
    case zh
    case en
    case fr
    case ru
    case es

    var id: String { rawValue }

    var resolved: AppLanguage {
        if self != .system { return self }
        let code = Locale.preferredLanguages.first ?? "en"
        if code.hasPrefix("ar") { return .ar }
        if code.hasPrefix("zh") { return .zh }
        if code.hasPrefix("fr") { return .fr }
        if code.hasPrefix("ru") { return .ru }
        if code.hasPrefix("es") { return .es }
        return .en
    }

    var layoutDirection: LayoutDirection {
        resolved == .ar ? .rightToLeft : .leftToRight
    }

    var locale: Locale {
        switch resolved {
        case .ar: return Locale(identifier: "ar")
        case .zh: return Locale(identifier: "zh_CN")
        case .fr: return Locale(identifier: "fr_FR")
        case .ru: return Locale(identifier: "ru_RU")
        case .es: return Locale(identifier: "es_ES")
        default: return Locale(identifier: "en_US")
        }
    }

    var nativeName: String {
        switch self {
        case .system: return L10n.s(.followSystem)
        case .ar: return "العربية"
        case .zh: return "中文"
        case .en: return "English"
        case .fr: return "Français"
        case .ru: return "Русский"
        case .es: return "Español"
        }
    }
}

